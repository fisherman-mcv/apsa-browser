import AppKit

// The interface is written in English; other languages translate those strings.
// A language holds from launch to quit, so a window never mixes two.
enum ApsaLanguage: String, CaseIterable {
    case english = "en"
    case russian = "ru"

    private static let key = "apsa-browser-language"
    static var saved: ApsaLanguage {
        get { UserDefaults.standard.string(forKey: key).flatMap(ApsaLanguage.init(rawValue:)) ?? .english }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: key) }
    }
    static let current = saved

    var name: String { self == .english ? "English" : "Русский" }
    var locale: Locale { Locale(identifier: self == .english ? "en_US" : "ru_RU") }
    var table: [String: String] { self == .english ? [:] : russianStrings }

    // What macOS draws for the app follows too: the page context menu, file panels.
    static func applyToSystemStrings() {
        UserDefaults.standard.set([current.rawValue], forKey: "AppleLanguages")
    }

    // The Mac's own language, which the setting above hides from Locale.
    static var systemLanguage: String? {
        let languages = CFPreferencesCopyValue("AppleLanguages" as CFString, kCFPreferencesAnyApplication, kCFPreferencesCurrentUser, kCFPreferencesAnyHost) as? [String]
        return languages?.first ?? Locale.preferredLanguages.first
    }

    // Opens again only after this process is gone, once the session is saved.
    static func relaunch() {
        let waiter = Process()
        waiter.executableURL = URL(fileURLWithPath: "/bin/sh")
        waiter.arguments = ["-c", "while kill -0 \"$0\" 2>/dev/null; do sleep 0.1; done; exec /usr/bin/open \"$1\"", String(getpid()), Bundle.main.bundlePath]
        guard (try? waiter.run()) != nil else { return }
        NSApp.terminate(nil)
    }
}

func apsaText(_ text: String, in language: ApsaLanguage = .current) -> String {
    language.table[text] ?? text
}

func apsaText(_ format: String, _ first: CVarArg, _ rest: CVarArg...) -> String {
    String(format: apsaText(format), arguments: [first] + rest)
}

